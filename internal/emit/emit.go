// Package emit lowers a checked Riddim program to Go (DESIGN §6): one Go file
// per source file with //line directives, the runtime, and a main wrapper.
package emit

import (
	_ "embed"
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strings"
	"unicode/utf8"

	"github.com/irie-people/riddim/internal/check"
	"github.com/irie-people/riddim/internal/syntax"
)

//go:embed rt.go.txt
var runtimeSrc string

// RuntimeDir is the directory of the runtime package, rt, in the module the
// generated Go is built in. The runtime is the same for every program, so
// Go's build cache compiles it once and reuses it across programs and edits.
const RuntimeDir = "rt"

// Runtime returns the source of the runtime package, to be written as
// rt/rt.go in the module.
func Runtime() ([]byte, error) { return format.Source([]byte(runtimeSrc)) }

// Program lowers p to the Go source files of package main, keyed by file
// name. lineName gives the file name to write in //line directives for each
// source, so that Go's messages and stack traces point at .rdm lines.
// runtime is the import path of the runtime package.
func Program(p *check.Program, lineName func(src *syntax.Source) string, runtime string) (map[string][]byte, error) {
	e := &emitter{prog: p, info: p.Info, lineName: lineName, runtime: runtime, tuples: map[int]bool{}, helpers: map[string]bool{}, globals: map[string]bool{}}
	for _, td := range p.Types {
		e.globals[td.Name] = true
	}
	for _, f := range p.Funcs {
		e.globals[goName(f.Name)] = true
	}
	for _, k := range p.Consts {
		e.globals[k.Name] = true
	}
	out := map[string][]byte{}
	for _, f := range p.Files {
		src, err := e.file(f)
		if err != nil {
			return nil, err
		}
		out[GoFileName(f.Source.Name)] = src
	}
	if tuples := e.tupleTypes() + e.helperFuncs(); tuples != "" {
		head := "// Code generated by riddim. DO NOT EDIT.\n\n// The tuple types this program uses, and the helpers that use them.\n\npackage main\n"
		if e.helpers["mapEntries"] {
			head += fmt.Sprintf("\nimport %q\n", e.runtime)
		}
		src, err := format.Source([]byte(head + tuples))
		if err != nil {
			return nil, fmt.Errorf("tuple types: %v", err)
		}
		out["riddim_tuples.go"] = src
	}
	if p.Main != nil {
		m, err := format.Source([]byte(e.mainWrapper()))
		if err != nil {
			return nil, fmt.Errorf("main wrapper: %v", err)
		}
		out["riddim_main.go"] = m
	}
	return out, nil
}

// GoFileName names the Go file made from a .rdm file: main.rdm gives
// main.rdm.go, which no _test or GOOS/GOARCH suffix rule can match.
func GoFileName(rdm string) string {
	base := filepath.Base(rdm)
	if strings.HasPrefix(base, "_") || strings.HasPrefix(base, ".") {
		base = "r" + base
	}
	return base + ".go"
}

type emitter struct {
	prog     *check.Program
	info     *check.Info
	lineName func(*syntax.Source) string
	runtime  string // the runtime package's import path
	tuples   map[int]bool
	helpers  map[string]bool // the onDemand helpers the program uses
	globals  map[string]bool // Go names of top-level declarations

	// per file
	imports map[string]bool
	w       *strings.Builder
}

func (e *emitter) printf(format string, args ...any) { fmt.Fprintf(e.w, format, args...) }

// rt names a member of the runtime package, which the current file then
// imports.
func (e *emitter) rt(name string) string {
	e.imports[e.runtime] = true
	return "rt." + name
}

// line writes a //line directive for pos.
func (e *emitter) line(pos syntax.Pos) {
	src := e.prog.Fset.Source(pos)
	l, _ := src.LineCol(pos)
	if s := e.w.String(); s != "" && s[len(s)-1] != '\n' {
		e.w.WriteString("\n")
	}
	fmt.Fprintf(e.w, "//line %s:%d\n", e.lineName(src), l)
}

func (e *emitter) file(f *syntax.File) ([]byte, error) {
	e.imports = map[string]bool{}
	body := &strings.Builder{}
	e.w = body
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *syntax.StructDecl:
			e.structDecl(e.info.TypeDecls[d])
		case *syntax.EnumDecl:
			e.enumDecl(e.info.TypeDecls[d])
		case *syntax.ConstDecl:
			e.constDecl(e.info.Consts[d])
		case *syntax.FuncDecl:
			e.funcDecl(e.info.Funcs[d])
		case *syntax.ImplDecl:
			if len(d.Doc) > 0 {
				// Go has no impl blocks: the comment stands alone above the methods.
				e.doc(d.Doc)
				e.printf("\n")
			}
			for _, m := range d.Methods {
				e.funcDecl(e.info.Funcs[m])
			}
		}
		e.printf("\n")
	}
	var head strings.Builder
	fmt.Fprintf(&head, "// Code generated by riddim from %s. DO NOT EDIT.\n\npackage main\n", filepath.Base(f.Source.Name))
	if len(e.imports) > 0 {
		var names []string
		for n := range e.imports {
			names = append(names, n)
		}
		sort.Strings(names)
		head.WriteString("\nimport (\n")
		for _, n := range names {
			fmt.Fprintf(&head, "\t%q\n", n)
		}
		head.WriteString(")\n")
	}
	src := head.String() + body.String()
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("%s: generated Go does not parse: %v\n%s", f.Source.Name, err, numbered(src))
	}
	return out, nil
}

func numbered(src string) string {
	lines := strings.Split(src, "\n")
	for i := range lines {
		lines[i] = fmt.Sprintf("%4d  %s", i+1, lines[i])
	}
	return strings.Join(lines, "\n")
}

func (e *emitter) tupleTypes() string {
	var ns []int
	for n := range e.tuples {
		ns = append(ns, n)
	}
	sort.Ints(ns)
	var b strings.Builder
	for _, n := range ns {
		params := make([]string, n)
		for i := range params {
			params[i] = fmt.Sprintf("T%d", i)
		}
		fmt.Fprintf(&b, "\n// Tuple_%d is a tuple of %d fields.\ntype Tuple_%d[%s any] struct {\n", n, n, n, strings.Join(params, ", "))
		for i := 0; i < n; i++ {
			fmt.Fprintf(&b, "\tf%d T%d\n", i, i)
		}
		b.WriteString("}\n")
	}
	return b.String()
}

// onDemand are runtime helpers that use generated tuple types, so they are
// written only into programs that use them.
var onDemand = map[string]string{
	"mapEntries": `
// mapEntries is Map.entries: the entries in order.
func mapEntries[K comparable, V any](m rt.Map[K, V]) []Tuple_2[K, V] {
	out := make([]Tuple_2[K, V], len(m.Keys))
	for i, k := range m.Keys {
		out[i] = Tuple_2[K, V]{k, m.Vals[i]}
	}
	return out
}
`,
	"listEnumerate": `
// listEnumerate is List.enumerate: each element with its index.
func listEnumerate[T any](xs []T) []Tuple_2[int, T] {
	out := make([]Tuple_2[int, T], len(xs))
	for i, x := range xs {
		out[i] = Tuple_2[int, T]{i, x}
	}
	return out
}
`,
}

// helper records that the program uses an onDemand helper, which needs the
// two-field tuple type.
func (e *emitter) helper(name string) {
	e.helpers[name] = true
	e.tuples[2] = true
}

func (e *emitter) helperFuncs() string {
	var names []string
	for n := range e.helpers {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, n := range names {
		b.WriteString(onDemand[n])
	}
	return b.String()
}

func (e *emitter) mainWrapper() string {
	m := e.prog.Main
	arg := ""
	if len(m.Params) == 1 {
		arg = "rt.NewSys()"
	}
	body := fmt.Sprintf("\tmain_(%s)\n", arg)
	if _, ok := check.Resolve(m.Result).(*check.Result); ok {
		body = fmt.Sprintf("\tif r := main_(%s); !r.IsOk {\n\t\trt.ExitWithError(r.Err)\n\t}\n", arg)
	}
	imp := ""
	if strings.Contains(body, "rt.") {
		imp = fmt.Sprintf("import %q\n\n", e.runtime)
	}
	return "// Code generated by riddim. DO NOT EDIT.\n\npackage main\n\n" + imp + "func main() {\n" + body + "}\n"
}

// ---- Names ----

// goReserved are Go keywords, predeclared identifiers and the names of the
// packages generated code imports. A Riddim name equal to one gets a `_`
// suffix. Riddim names cannot end in `_`, so this cannot clash.
var goReserved = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`break case chan const continue default defer else fallthrough for func go goto
		if import interface map package range return select struct switch type var
		any bool byte comparable complex64 complex128 error float32 float64 int int8 int16 int32 int64
		rune string uint uint8 uint16 uint32 uint64 uintptr true false iota nil
		append cap clear close complex copy delete imag len make max min new panic print println real recover
		main init errors fmt math os strconv strings unicode utf8 rt`) {
		goReserved[w] = true
	}
}

func goName(name string) string {
	if goReserved[name] {
		return name + "_"
	}
	return name
}

func typeArgs(ts []string) string {
	if len(ts) == 0 {
		return ""
	}
	return "[" + strings.Join(ts, ", ") + "]"
}

func (e *emitter) typeList(ts []check.Type) []string {
	out := make([]string, len(ts))
	for i, t := range ts {
		out[i] = e.goType(t)
	}
	return out
}

// goType returns the Go type of a Riddim type.
func (e *emitter) goType(t check.Type) string {
	switch t := check.Deep(t).(type) {
	case *check.Basic:
		switch t {
		case check.Int:
			return "int"
		case check.Float:
			return "float64"
		case check.Bool:
			return "bool"
		case check.String:
			return "string"
		case check.Byte:
			return "byte"
		case check.ErrorT:
			return "error"
		}
		return "struct{}" // () and Never
	case *check.Tuple:
		e.tuples[len(t.Elems)] = true
		return fmt.Sprintf("Tuple_%d%s", len(t.Elems), typeArgs(e.typeList(t.Elems)))
	case *check.List:
		return "[]" + e.goType(t.Elem)
	case *check.Map:
		return e.rt("Map") + "[" + e.goType(t.Key) + ", " + e.goType(t.Val) + "]"
	case *check.Option:
		return e.rt("Option") + "[" + e.goType(t.Elem) + "]"
	case *check.Result:
		return e.rt("Result") + "[" + e.goType(t.Ok) + ", " + e.goType(t.Err) + "]"
	case *check.Func:
		return "func(" + strings.Join(e.typeList(t.Params), ", ") + ") " + e.goType(t.Result)
	case *check.Named:
		return t.Decl.Name + typeArgs(e.typeList(t.Args))
	case *check.TypeParam:
		return t.Name
	case *check.Cap:
		return e.rt(t.Name)
	}
	return "struct{}"
}

// resultType returns the Go result of a declared function: none for () and
// Never.
func (e *emitter) resultType(t check.Type) string {
	r := check.Resolve(t)
	if r == check.Unit || r == check.Never {
		return ""
	}
	return " " + e.goType(t)
}

func noResult(t check.Type) bool {
	r := check.Resolve(t)
	return r == check.Unit || r == check.Never
}

func tparamList(tps []*check.TypeParam) string {
	if len(tps) == 0 {
		return ""
	}
	names := make([]string, len(tps))
	for i, tp := range tps {
		names[i] = tp.Name
	}
	return "[" + strings.Join(names, ", ") + " any]"
}

func tparamNames(tps []*check.TypeParam) []string {
	names := make([]string, len(tps))
	for i, tp := range tps {
		names[i] = tp.Name
	}
	return names
}

// variantType returns the Go type of an enum variant's struct.
func (e *emitter) variantType(v *check.Variant, args []check.Type) string {
	return v.Enum.Name + "_" + v.Name + typeArgs(e.typeList(args))
}

func fieldName(f *check.Field) string {
	if f.Name == "" {
		return fmt.Sprintf("f%d", f.Index)
	}
	return goName(f.Name)
}

// ---- Declarations ----

// doc writes a /// comment as a Go comment, above the //line directive of
// its declaration so that Go reads it as the declaration's doc comment. A
// space after // keeps a line such as `///line x` from becoming a directive,
// and characters Go does not allow in source, such as NUL or invalid UTF-8,
// become U+FFFD.
func (e *emitter) doc(lines []string) {
	for _, l := range lines {
		l = strings.Map(func(r rune) rune {
			if r < ' ' && r != '\t' || r == 0x7f || r == 0xfeff {
				return utf8.RuneError
			}
			return r
		}, strings.ToValidUTF8(l, string(utf8.RuneError)))
		if l = strings.TrimPrefix(l, " "); l == "" {
			e.printf("//\n")
		} else {
			e.printf("// %s\n", l)
		}
	}
}

func (e *emitter) structDecl(td *check.TypeDecl) {
	d := td.Decl.(*syntax.StructDecl)
	e.doc(d.Doc)
	e.line(td.Ident.NamePos)
	if len(td.Fields) == 0 {
		e.printf("type %s%s struct{}\n", td.Name, tparamList(td.TParams))
		return
	}
	e.printf("type %s%s struct {\n", td.Name, tparamList(td.TParams))
	for i, f := range td.Fields {
		e.doc(d.Fields[i].Doc)
		e.printf("%s %s\n", fieldName(f), e.goType(f.Type))
	}
	e.printf("}\n")
}

func (e *emitter) enumDecl(td *check.TypeDecl) {
	d := td.Decl.(*syntax.EnumDecl)
	e.doc(d.Doc)
	e.line(td.Ident.NamePos)
	if td.Fieldless() {
		e.printf("type %s int\n\nconst (\n", td.Name)
		for i, v := range td.Variants {
			e.doc(d.Variants[i].Doc)
			if i == 0 {
				e.printf("%s_%s %s = iota\n", td.Name, v.Name, td.Name)
			} else {
				e.printf("%s_%s\n", td.Name, v.Name)
			}
		}
		e.printf(")\n")
		return
	}
	tps := tparamList(td.TParams)
	args := typeArgs(tparamNames(td.TParams))
	marker := "is" + td.Name
	e.printf("type %s%s interface {\n%s()\n}\n", td.Name, tps, marker)
	for i, v := range td.Variants {
		e.printf("\n")
		e.doc(d.Variants[i].Doc)
		if len(v.Fields) == 0 {
			e.printf("type %s_%s%s struct{}\n", td.Name, v.Name, tps)
			continue
		}
		e.printf("type %s_%s%s struct {\n", td.Name, v.Name, tps)
		for _, f := range v.Fields {
			e.printf("%s %s\n", fieldName(f), e.goType(f.Type))
		}
		e.printf("}\n")
	}
	e.printf("\n")
	for _, v := range td.Variants {
		e.printf("func (%s_%s%s) %s() {}\n", td.Name, v.Name, args, marker)
	}
}

func (e *emitter) constDecl(k *check.ConstObj) {
	e.doc(k.Decl.Doc)
	e.line(k.Decl.Const)
	f := e.newFunc(nil)
	e.printf("const %s %s = %s\n", k.Name, e.goType(k.Type), f.exprVal(k.Decl.Value))
}

func (e *emitter) funcDecl(fo *check.FuncObj) {
	if fo == nil {
		return
	}
	f := e.newFunc(fo)
	var params []string
	for i, l := range fo.ParamLocals {
		params = append(params, f.bind(l)+" "+e.goType(fo.Params[i]))
	}
	name := goName(fo.Name)
	if fo == e.prog.Main {
		name = "main_"
	}
	e.doc(fo.Decl.Doc)
	e.line(fo.Decl.Fn)
	switch {
	case fo.Recv == nil:
		e.printf("func %s%s(%s)%s {\n", name, tparamList(fo.TParams), strings.Join(params, ", "), e.resultType(fo.Result))
	case !fo.Recv.IsEnum && fo.HasSelf:
		recv := fo.Recv.Name + typeArgs(tparamNames(fo.ImplTParams))
		e.printf("func (%s %s) %s%s(%s)%s {\n", f.bind(fo.SelfLocal), recv, name, tparamList(fo.TParams), strings.Join(params, ", "), e.resultType(fo.Result))
	default:
		// Enum methods and associated functions are functions named Type_name.
		tps := append(append([]*check.TypeParam{}, fo.ImplTParams...), fo.TParams...)
		if fo.HasSelf {
			recv := fo.Recv.Name + typeArgs(tparamNames(fo.ImplTParams))
			params = append([]string{f.bind(fo.SelfLocal) + " " + recv}, params...)
		}
		e.printf("func %s_%s%s(%s)%s {\n", fo.Recv.Name, fo.Name, tparamList(tps), strings.Join(params, ", "), e.resultType(fo.Result))
	}
	f.body(fo.Decl.Body, fo.Result)
	e.printf("}\n")
}
